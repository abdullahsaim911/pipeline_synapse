"""
POST /video/quiz: transcript-grounded practice questions (PROPOSED contract; on by default in development, off in production).

The endpoint answers 404 "Quiz is not available." when the flag is off (see quiz/config.py: an explicit
QUIZ_ENABLED decides; unset means on in development and off when SYNAPSE_ENV=production). Questions are generated by an LLM and only SCREENED (rejection
filter) before being returned: screening is not proof that a question or its answer key is
correct, and the human-reviewed quality gate is a separate stage.

Declared as a plain `def` so FastAPI runs it in a worker thread: the database, file and LLM
calls block and must not stall the event loop.
"""

import logging
import os
import traceback
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from api.database import get_db
from api.models import Video
from api.routers.video import get_data_dir
from api.security import enforce_allowed_origin
from llm_interface.providers import (
    LLMConfigurationError,
    LLMConnectionError,
    LLMProviderError,
    LLMRateLimitError,
    LLMTimeoutError,
    LLMUnavailableError,
)
from qa.transcript import load_transcript
from quiz.config import quiz_enabled
from quiz.schemas import QuizRequest, QuizResponse
from quiz.service import QuizBusyError, QuizDeadlineError, QuizService, QuizUnusableOutputError

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/video", tags=["quiz"])

_quiz_service: Optional[QuizService] = None


def get_quiz_service() -> QuizService:
    """Shared QuizService (dependency, so tests can substitute a fake provider). No provider is built until needed."""
    global _quiz_service
    if _quiz_service is None:
        _quiz_service = QuizService()
    return _quiz_service


def require_quiz_enabled() -> None:
    """Runs before body validation, so a disabled endpoint reveals nothing else."""
    if not quiz_enabled():
        raise HTTPException(status_code=404, detail="Quiz is not available.")


def _llm_http_error(exc: LLMProviderError) -> HTTPException:
    """Provider failure -> HTTP error, without provider details."""
    if isinstance(exc, LLMRateLimitError):
        return HTTPException(status_code=429, detail="The AI service is busy or over its quota. Please try again shortly.")
    if isinstance(exc, LLMTimeoutError):
        return HTTPException(status_code=504, detail="The AI service took too long to respond. Please try again.")
    if isinstance(exc, (LLMConnectionError, LLMUnavailableError)):
        return HTTPException(status_code=503, detail="The AI service is temporarily unavailable. Please try again.")
    if isinstance(exc, LLMConfigurationError):
        return HTTPException(status_code=500, detail="Quiz generation is not configured on this server.")
    return HTTPException(status_code=500, detail="Could not create the quiz.")


@router.post(
    "/quiz",
    response_model=QuizResponse,
    dependencies=[Depends(require_quiz_enabled), Depends(enforce_allowed_origin)],
)
def create_quiz(
    request: QuizRequest,
    db: Session = Depends(get_db),
    service: QuizService = Depends(get_quiz_service),
    data_dir: str = Depends(get_data_dir),
):
    """
    Create 5 to 10 multiple-choice / true-false practice questions for a lecture.

    Input:  {"video_id": "3zLQfuMZMF4", "question_count": 6}   (question_count optional, default 6)
    Output: status complete | partial | insufficient_material, with questions whose evidence
            times and quotes are computed by the server from the transcript.
    """
    try:
        transcript = load_transcript(request.video_id, db, data_dir)

        video = db.query(Video).filter(Video.id == request.video_id).first()
        if video is None and not transcript.file_exists:
            raise HTTPException(status_code=404, detail="Video not found")

        return service.generate(request.video_id, request.question_count, transcript.segments)

    except HTTPException:
        raise
    except QuizBusyError:
        raise HTTPException(status_code=429, detail="A quiz is already being created for this video. Please try again shortly.")
    except QuizDeadlineError:
        raise HTTPException(status_code=504, detail="The AI service took too long to respond. Please try again.")
    except QuizUnusableOutputError:
        raise HTTPException(status_code=502, detail="The AI service returned an unusable response. Please try again.")
    except LLMProviderError as exc:
        logger.warning("Quiz failed for video %s: %s (upstream status %s)", request.video_id, exc.code, exc.status_code)
        raise _llm_http_error(exc)
    except Exception as exc:
        # Type and location only: exception messages (for example validation errors) can quote
        # transcript, model or candidate text, which must never reach the logs.
        frame = traceback.extract_tb(exc.__traceback__)[-1]
        logger.error("Unexpected error creating a quiz for video %s: %s at %s:%d", request.video_id,
                     type(exc).__name__, os.path.basename(frame.filename), frame.lineno)
        raise HTTPException(status_code=500, detail="Could not create the quiz.")
